#!/usr/bin/env python3
"""Print requirements-overlay.lock: every distribution the requirements in argv[1] need,
transitively, pinned to the version installed in the running interpreter.

Regenerate inside the base image named in server/Dockerfile:
  docker run --rm -v "$PWD:/w" --entrypoint sh <SERVER_BASE_IMAGE> -c \\
    'pip install -q -r /w/requirements-overlay.txt && python /w/scripts/lock_overlay_deps.py /w/requirements-overlay.txt' \\
    > requirements-overlay.lock
"""
import sys
from importlib import metadata

from pip._vendor.packaging.requirements import Requirement
from pip._vendor.packaging.utils import canonicalize_name


def closure(roots):
    found = {}
    stack = list(roots)
    while stack:
        req = stack.pop()
        key = canonicalize_name(req.name)
        extras = set(req.extras)
        if key in found and extras <= found[key][1]:
            continue
        dist = metadata.distribution(req.name)
        extras |= found.get(key, (None, set()))[1]
        found[key] = (f"{dist.metadata['Name']}=={dist.version}", extras)
        for spec in dist.requires or []:
            dep = Requirement(spec)
            if dep.marker is None or any(dep.marker.evaluate({"extra": e}) for e in extras | {""}):
                stack.append(dep)
    return [pin for _, (pin, _) in sorted(found.items())]


def main(path):
    with open(path, encoding="utf-8") as f:
        roots = [Requirement(line.split("#")[0].strip()) for line in f if line.split("#")[0].strip()]
    print("# Generated by scripts/lock_overlay_deps.py from requirements-overlay.txt; do not edit.")
    for pin in closure(roots):
        print(pin)


if __name__ == "__main__":
    main(sys.argv[1])
