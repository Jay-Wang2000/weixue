#!/usr/bin/env python3
"""Generates the agent earcons and writes them as Ogg Opus (16 kHz mono, 60 ms frames, the
format of the upstream assets/common sounds) into a C++ header for AudioService::PlaySound.

  .venv/bin/pip install av            # PyAV wheels carry libopus
  .venv/bin/python firmware/tools/earcons.py            # rewrites the header
  .venv/bin/python firmware/tools/earcons.py --check    # exit 1 if the header differs
  .venv/bin/python firmware/tools/earcons.py --wav-dir /tmp/earcons   # also writes PCM WAVs

One timbre family: a sine with a soft second and third harmonic, 6 ms attack, exponential decay;
two-tone figures or one chirp, 200-600 ms, peak -12 dBFS."""
import argparse
import io
import math
import os
import struct
import sys
import wave

RATE = 16000
PEAK = 10 ** (-12 / 20)
HEADER = os.path.join(os.path.dirname(__file__), "..", "overrides", "main", "boards", "waveshare",
                      "esp32-s3-touch-amoled-1.75", "agent_earcons.h")

# name -> list of (start_hz, end_hz, seconds, gap_after_seconds); end_hz != start_hz is a chirp.
EARCONS = {
    "needs_you": [(659.3, 659.3, 0.15, 0.03), (880.0, 880.0, 0.20, 0.0)],
    "approved": [(784.0, 784.0, 0.09, 0.02), (1046.5, 1046.5, 0.17, 0.0)],
    "denied": [(440.0, 440.0, 0.14, 0.03), (329.6, 329.6, 0.18, 0.0)],
    "done": [(1046.5, 1046.5, 0.12, 0.02), (1318.5, 1318.5, 0.22, 0.0)],
    "error": [(329.6, 329.6, 0.20, 0.05), (261.6, 261.6, 0.24, 0.0)],
    "chat_switch": [(600.0, 1200.0, 0.22, 0.0)],
}


def tone(f0, f1, seconds):
    n = int(seconds * RATE)
    out = []
    phase = 0.0
    attack = int(0.006 * RATE)
    for i in range(n):
        f = f0 + (f1 - f0) * i / max(1, n - 1)
        phase += 2 * math.pi * f / RATE
        env = min(1.0, i / attack) * math.exp(-3.2 * i / n) * min(1.0, (n - i) / (0.01 * RATE))
        v = math.sin(phase) + 0.25 * math.sin(2 * phase) + 0.08 * math.sin(3 * phase)
        out.append(env * v / 1.33)
    return out


def synth(parts):
    pcm = []
    for f0, f1, seconds, gap in parts:
        pcm += tone(f0, f1, seconds)
        pcm += [0.0] * int(gap * RATE)
    pcm += [0.0] * int(0.06 * RATE)
    return [max(-32768, min(32767, int(round(v * PEAK * 32767)))) for v in pcm]


def encode_ogg(samples):
    import av

    buf = io.BytesIO()
    out = av.open(buf, mode="w", format="ogg", options={"fflags": "+bitexact"})
    stream = out.add_stream("libopus", rate=RATE)
    stream.layout = "mono"
    stream.bit_rate = 24000
    stream.codec_context.flags |= av.codec.context.Flags.bitexact
    stream.options = {"frame_duration": "60", "application": "audio", "vbr": "off"}
    frame = av.AudioFrame(format="s16", layout="mono", samples=len(samples))
    frame.sample_rate = RATE
    frame.planes[0].update(struct.pack(f"<{len(samples)}h", *samples))
    for packet in stream.encode(frame):
        out.mux(packet)
    for packet in stream.encode(None):
        out.mux(packet)
    out.close()
    return buf.getvalue()


def write_wav(path, samples):
    with wave.open(path, "wb") as w:
        w.setnchannels(1)
        w.setsampwidth(2)
        w.setframerate(RATE)
        w.writeframes(struct.pack(f"<{len(samples)}h", *samples))


def header(blobs):
    lines = [
        "#ifndef WEIXUE_AGENT_EARCONS_H",
        "#define WEIXUE_AGENT_EARCONS_H",
        "",
        "// Generated by firmware/tools/earcons.py; do not edit.",
        "",
        "#include <string_view>",
        "",
        "namespace agent_earcons {",
        "",
    ]
    for name, (data, ms) in blobs.items():
        ident = "k" + "".join(p.capitalize() for p in name.split("_"))
        lines.append(f"// {name}: {ms} ms, {len(data)} bytes")
        lines.append(f"inline constexpr unsigned char {ident}[] = {{")
        for i in range(0, len(data), 16):
            lines.append("    " + ", ".join(f"0x{b:02x}" for b in data[i:i + 16]) + ",")
        lines.append("};")
        lines.append("")
    lines.append("// Ogg Opus bytes of an earcon by name (needs_you, approved, denied, done, error, chat_switch).")
    lines.append("inline std::string_view Get(std::string_view name) {")
    for name in blobs:
        ident = "k" + "".join(p.capitalize() for p in name.split("_"))
        lines.append(f"    if (name == \"{name}\") return {{reinterpret_cast<const char*>({ident}), sizeof({ident})}};")
    lines.append("    return {};")
    lines.append("}")
    lines.append("")
    lines.append("}  // namespace agent_earcons")
    lines.append("")
    lines.append("#endif  // WEIXUE_AGENT_EARCONS_H")
    return "\n".join(lines) + "\n"


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true", help="compare with the header instead of writing it")
    ap.add_argument("--wav-dir", help="also write <name>.wav (PCM) and <name>.ogg here")
    ap.add_argument("--out", default=HEADER, help="header path")
    args = ap.parse_args(argv)
    blobs = {}
    for name, parts in EARCONS.items():
        samples = synth(parts)
        ms = round(1000 * len(samples) / RATE)
        if not 200 <= ms <= 660:
            raise SystemExit(f"{name}: {ms} ms is outside 200-600 ms (+60 ms tail)")
        data = encode_ogg(samples)
        blobs[name] = (data, ms)
        if args.wav_dir:
            os.makedirs(args.wav_dir, exist_ok=True)
            write_wav(os.path.join(args.wav_dir, name + ".wav"), samples)
            with open(os.path.join(args.wav_dir, name + ".ogg"), "wb") as f:
                f.write(data)
        print(f"{name}: {ms} ms, {len(data)} bytes")
    text = header(blobs)
    if args.check:
        current = open(args.out).read() if os.path.exists(args.out) else ""
        if current != text:
            print(f"{args.out} differs from the generator output", file=sys.stderr)
            return 1
        print(f"{args.out} matches")
        return 0
    with open(args.out, "w") as f:
        f.write(text)
    print(f"wrote {os.path.normpath(args.out)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
